"""Element schemas for the shared site chrome: the header (launch ticker + nav + phone app bar) and the footer.

  uv run -q --with tinycss2 python -I tools/chrome.py   -> build/chrome-header.json, build/chrome-footer.json

Both become Webflow components used on every page. The header wraps three body-level mockup nodes in one
`site-header` div with display:contents, so the ticker and nav stay sticky against the page, not the wrapper.
Mockup-only nodes (`.note`) are dropped; page links are rewritten for the live site (Updates is /updates)."""
import json
import re

import mock2wf as m

LINKS = {"/blog-post": "/updates"}
FOOTER_HREF = {"Privacy": "/legal-pages/privacy-policy", "Terms": "/legal-pages/terms-of-service",
               "Cookies": "/legal-pages/cookie-consent-policy", "In the press": "/in-the-press"}


def body_nodes():
    t = m.Tree()
    src = (m.PAGES / "index.html").read_text()
    t.feed(re.search(r"<body[^>]*>(.*)</body>", src, re.S).group(1))
    return [k for k in t.root["kids"] if k["tag"] != "#text"]


def strip_notes(n):
    if n["tag"] == "#text":
        return n
    n["kids"] = [strip_notes(k) for k in n["kids"] if not (k["tag"] != "#text" and "note" in (k["attrs"].get("class") or "").split())]
    return n


def text_of(n):
    return "".join(k["text"] if k["tag"] == "#text" else text_of(k) for k in n["kids"])


def fix_links(n):
    if n["tag"] == "a":
        label = text_of(n).strip()
        if label in FOOTER_HREF:
            n["attrs"]["href"] = FOOTER_HREF[label]
    for k in n["kids"]:
        if k["tag"] != "#text":
            fix_links(k)
    return n


def relink(s):
    if "set_link" in s:
        s["set_link"]["link"] = LINKS.get(s["set_link"]["link"], s["set_link"]["link"])
    for c in s.get("children", []):
        relink(c)
    return s


def pick(nodes, cls):
    return next(n for n in nodes if cls in (n["attrs"].get("class") or "").split())


CHROME = re.compile(r"\.(site-header|status_|nav_|appbar|footer_|updates_|post\b|post_|rich-text-section)")  # blog cards and the legal template render on pages without site.css (Updates, blog template, legal pages)


def chrome_css():
    """The header/footer (and blog card) rules out of styles/site.css, for the site-wide head: pages not rebuilt yet (Updates, In the Press,
    CMS templates) get the new chrome without site.css's global body/img/a rules."""
    import tinycss2
    sheet = tinycss2.parse_stylesheet((m.HERE / "styles" / "site.css").read_text(), skip_comments=True, skip_whitespace=True)
    used_frames, out = {"ticker", "pulse"}, []  # named in Webflow class styles (status_track, status_pulse), not in site.css

    def keep(rules, wrap=None):
        kept = []
        for r in rules:
            if r.type == "qualified-rule":
                sels = [s for s in m.split_top(tinycss2.serialize(r.prelude)) if CHROME.search(s)]  # top-level commas only: :is(a,b) stays whole
                if sels:
                    body = tinycss2.serialize(r.content)
                    used_frames.update(re.findall(r"animation(?:-name)?\s*:\s*([\w-]+)", body))
                    kept.append(",".join(s.strip() for s in sels) + "{" + body + "}")
            elif r.type == "at-rule" and r.lower_at_keyword in ("media", "supports") and r.content:
                inner = keep(tinycss2.parse_rule_list(r.content, skip_comments=True, skip_whitespace=True))
                if inner:
                    kept.append(f"@{r.lower_at_keyword} {tinycss2.serialize(r.prelude).strip()}{{{''.join(inner)}}}")
        return kept
    out = keep(sheet)
    frames = [tinycss2.serialize([r]) for r in sheet if r.type == "at-rule" and r.lower_at_keyword == "keyframes"
              and tinycss2.serialize(r.prelude).strip() in used_frames]
    text = "/* Generated by tools/chrome.py from styles/site.css: header + footer rules only, loaded site-wide. */\n" + "\n".join(out + frames) + "\n"
    (m.HERE / "styles" / "chrome.css").write_text(text)
    print(f"styles/chrome.css {len(text)} chars, keyframes {sorted(used_frames)}")


def main():
    chrome_css()
    nodes = body_nodes()
    ids, report = m.assets(), []
    parts = [m.schema(strip_notes(fix_links(pick(nodes, c))), ids, report) for c in ("status_component", "nav_component", "appbar")]
    header = relink({"type": "BY_CUSTOM_TAG", "custom_tag": "div", "set_style": {"style_names": ["site-header"]}, "children": parts})
    footer = relink(m.schema(strip_notes(fix_links(pick(nodes, "footer_component"))), ids, report))
    m.OUT.mkdir(exist_ok=True)
    for name, s in (("header", header), ("footer", footer)):
        (m.OUT / f"chrome-{name}.json").write_text(json.dumps(s, indent=1))
        print(f"chrome-{name}.json {len(json.dumps(s))} chars")
    for r in sorted(set(report)):
        print("  !", r)


if __name__ == "__main__":
    main()
