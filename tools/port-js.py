"""Bundle the approved mockup behavior into islands/site.js for Webflow (one hosted script, after GSAP + ScrollTrigger).

Order matches the mockup page: v2.js, v3.js, appsim-routes.js, appsim.js, then the Webflow-only islands (app-link, mux-video).
Strips the "// Mockup only:" IIFEs (notes toggle, blog before/after, review bar). Query switches (?part=, ?tour=, ?static) stay
for QA links. Every block returns early when its root element is absent, so the bundle is safe on every rebuilt page.
Run: python3 -I tools/port-js.py   then   python3 -I tools/sri.py site"""
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent.parent
SITE = HERE.parent.parent / "projects" / "launch-site"
SOURCES = [SITE / "mockup-v2/v2.js", SITE / "mockup-v3/v3.js", SITE / "mockup-v3/appsim-routes.js", SITE / "mockup-v3/appsim.js",
           HERE / "islands/app-link.js", HERE / "islands/mux-video.js"]
MOCK_ONLY = re.compile(r"// Mockup only:[^\n]*\n\(function \(\) \{.*?\n\}\)\(\);\n?", re.S)


def sprites():
    """The mockup's hidden SVG sprites (step/sign/community icons + the rail lighthouse defs), injected at the top of <body>.
    Webflow has no page-level place for them outside an embed, and every rebuilt page needs the same set."""
    src = (SITE / "mockup-v3-ian" / "index.html").read_text()
    found = []
    for m in re.finditer(r"<svg[^>]*>(?:(?!</svg>).)*?<symbol id=\"(dcb-[a-z-]+)\".*?</svg>", src, re.S):
        if m.group(0) not in found:
            found.append(m.group(0))
    blob = re.sub(r">\s+<", "><", "".join(found)).replace("\\", "\\\\").replace("'", "\\'")
    return ("/* ---- icon sprites (from mockup-v3-ian/index.html) ---- */\n(function () {\n"
            "  if (document.getElementById(\"dcb-sprites\")) return;\n"
            f"  var d = document.createElement(\"div\"); d.id = \"dcb-sprites\"; d.setAttribute(\"aria-hidden\", \"true\"); d.style.cssText = \"position:absolute;width:0;height:0;overflow:hidden\"; d.innerHTML = '{blob}';\n"
            "  document.body.insertBefore(d, document.body.firstChild);\n})();\n"), len(found)


def main():
    sprite_js, n_sprites = sprites()
    parts, dropped = [sprite_js], 0
    for src in SOURCES:
        body, n = MOCK_ONLY.subn("", src.read_text())
        dropped += n
        parts.append(f"/* ---- {src.name} ---- */\n{body.strip()}\n")
    head = "/* Drifters City Bike site behavior. Generated by tools/port-js.py from the approved mockup; do not edit by hand. */\n"
    out = HERE / "islands" / "site.js"
    out.write_text(head + "\n".join(parts))
    print(f"islands/site.js {out.stat().st_size // 1024} KB, {dropped} mockup-only blocks removed, {n_sprites} sprite svgs")


main()
